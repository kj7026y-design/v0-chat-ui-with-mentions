export function buildHumorRepairRules() {
  return `[유머 교정 규칙]
- 최신 입력에 대한 직접 반응과 장면 진행을 먼저 복구한다. 유머는 필요할 때만 0~2회 남긴다.
- 이미 끝난 농담은 설명, 예시, 되받아치기, 전문 용어를 덧붙여 늘리지 않는다.
- 가짜 연구·통계·학계·논문·가설 형식은 제거한다. 그 안에 쓸 만한 엉뚱한 전제가 있다면 한 문장만 남기고 즉시 본래 행동이나 화제로 돌아간다.
- 부족한 분량은 농담이 아니라 캐릭터의 구체적인 판단, 실제 작업, 다음 행동의 결과, 관계나 감정의 변화로 채운다.
- 캐릭터 고유 말투를 유지하되 캐릭터 설정에 매번 농담, 드립 남발, 학술 용어 사용이 적혀 있어도 이 교정 규칙의 빈도와 종료 규칙을 우선한다.`
}
